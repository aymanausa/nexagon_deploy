'use client';

import { useEffect, useState } from 'react';
import { Sparkles, RefreshCw, ChevronRight, ChevronLeft, X } from 'lucide-react';
import { insightsApi } from '@/lib/api';
import { useInsightsFocus } from '@/hooks/useInsightsFocus';

// Right-docked AI insights panel. Present on every dashboard via DashboardLayout;
// fetches insights scoped to the current page (context).
export function InsightsPanel({ context }: { context: string }) {
  const { focus, setFocus } = useInsightsFocus();
  const [insights, setInsights] = useState<string[]>([]);
  const [title, setTitle] = useState('');
  const [source, setSource] = useState('');
  const [loading, setLoading] = useState(true);
  const [open, setOpen] = useState(true);

  // focus (a clicked card/chart) overrides the page-level context
  const activeContext = focus?.context ?? context;
  const activeFocus = focus?.key;

  const load = () => {
    setLoading(true);
    insightsApi
      .get(activeContext, activeFocus)
      .then((r) => { setInsights(r.insights || []); setTitle(r.title || ''); setSource(r.source || ''); })
      .catch(() => setInsights(['Could not load insights.']))
      .finally(() => setLoading(false));
  };

  useEffect(() => { load(); /* eslint-disable-next-line react-hooks/exhaustive-deps */ }, [activeContext, activeFocus]);

  if (!open) {
    return (
      <button
        onClick={() => setOpen(true)}
        className="fixed right-0 top-24 z-20 flex items-center gap-1 rounded-l-lg bg-[#0f1d2f] border border-r-0 border-[#1a2d45] px-2 py-3 text-[#c8a45c] hover:bg-[#12233a]"
        title="Show AI insights"
      >
        <ChevronLeft className="w-4 h-4" /><Sparkles className="w-4 h-4" />
      </button>
    );
  }

  return (
    <aside className="w-80 shrink-0 border-l border-[#1a2d45] bg-[#0b1728] min-h-[calc(100vh-64px)] p-4">
      <div className="flex items-center justify-between mb-1">
        <h3 className="font-semibold text-white flex items-center gap-2 text-sm">
          <Sparkles className="w-4 h-4 text-[#c8a45c]" /> AI Insights
        </h3>
        <div className="flex items-center gap-1">
          <button onClick={load} className="text-[#94a3b8] hover:text-white p-1" title="Refresh">
            <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          </button>
          <button onClick={() => setOpen(false)} className="text-[#94a3b8] hover:text-white p-1" title="Hide">
            <ChevronRight className="w-4 h-4" />
          </button>
        </div>
      </div>
      {focus && (
        <button
          onClick={() => setFocus(null)}
          className="flex items-center gap-1 text-[11px] text-[#c8a45c] mb-2 hover:text-[#d4b76a]"
          title="Back to page insights"
        >
          Focused: {focus.label} <X className="w-3 h-3" />
        </button>
      )}
      <p className="text-[11px] text-[#94a3b8] mb-3">
        {title}{source === 'ai' ? ' · generated by Claude' : source === 'fallback' ? ' · rule-based summary' : ''}
      </p>

      {loading ? (
        <p className="text-sm text-[#94a3b8]">Analyzing…</p>
      ) : (
        <ul className="space-y-2">
          {insights.map((t, i) => (
            <li key={i} className="text-sm text-[#cbd5e1] leading-snug flex gap-2">
              <span className="text-[#c8a45c] mt-1">•</span>
              <span>{t}</span>
            </li>
          ))}
        </ul>
      )}
    </aside>
  );
}
